/// Glyph bitmap for one byte: printable ASCII indexes [`FONT`],
/// anything else is [`BLOCK`].
pub fn glyph_for(ch: u8) -> [u8; 8] {
    if (0x20..=0x7E).contains(&ch) {
        FONT[(ch - 0x20) as usize]
    } else {
        BLOCK
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn font_covers_all_printable_ascii() {
        assert_eq!(FONT.len(), 95);
        // Space is blank, '~' is not, and no glyph is accidentally
        // all-zero except space.
        assert_eq!(FONT[0], [0; 8]);
        assert_ne!(FONT[95 - 1], [0; 8]);
        for (i, g) in FONT.iter().enumerate() {
            if i != 0 {
                assert_ne!(*g, [0; 8], "glyph {:#x} is blank", i + 0x20);
            }
        }
    }

    #[test]
    fn glyph_for_maps_printable_and_block() {
        assert_eq!(glyph_for(b'A'), FONT[(b'A' - 0x20) as usize]);
        assert_eq!(glyph_for(b' '), FONT[0]);
        assert_eq!(glyph_for(b'~'), FONT[94]);
        assert_eq!(glyph_for(0x00), BLOCK);
        assert_eq!(glyph_for(0x1B), BLOCK);
        assert_eq!(glyph_for(0x7F), BLOCK);
        assert_eq!(glyph_for(0xE2), BLOCK);
    }

    #[test]
    fn digit_glyphs_are_distinct() {
        for a in b'0'..=b'9' {
            for b in (a + 1)..=b'9' {
                assert_ne!(glyph_for(a), glyph_for(b), "{a} vs {b}");
            }
        }
    }
}
