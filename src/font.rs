//! Embedded bitmap font: one 8-row glyph per printable ASCII character
//! (`0x20`..=`0x7E`), drawn doubled vertically into 8x16 cells by
//! [`crate::Framebuffer::draw_glyph`].
//!
//! The glyphs are hand-drawn (no external font file — crates.io is not
//! reachable from the build VM, so no font crate could be fetched).
//! Each row is one byte, MSB on the left; `#` in the comments below
//! would be a set pixel. The design is a plain 8x8 sans: capitals and
//! digits fill the full cell, lowercase sits on rows 2–6 with
//! descenders (`g`, `j`, `p`, `q`, `y`) dropping to row 7.
//!
//! Bytes outside the printable range do not index this table: the
//! renderer draws [`BLOCK`] (a solid block) instead, matching the VGA
//! console's `0xFE` treatment of non-printables.

/// Width of one glyph, in pixels.
pub const GLYPH_WIDTH: usize = 8;
/// Rows per glyph in this table.
pub const GLYPH_HEIGHT: usize = 8;

/// Solid block, drawn for non-printable bytes (same role as the VGA
/// console's `0xFE`).
pub const BLOCK: [u8; 8] = [0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF];

